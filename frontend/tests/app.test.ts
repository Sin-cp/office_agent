// @vitest-environment jsdom
import { mount, flushPromises } from '@vue/test-utils';
import { expect, it, vi } from 'vitest';
import App from '../src/App.vue';
import Composer from '../src/components/Composer.vue';
import FileDrawer from '../src/components/FileDrawer.vue';
import DocumentEditor from '../src/components/DocumentEditor.vue';
import { listFiles, uploadFile, readDocument } from '../src/api';
vi.mock('../src/api', () => ({ listFiles: vi.fn(), uploadFile: vi.fn(), readDocument: vi.fn(), downloadUrl: (id: string) => `/api/files/${id}/download`, formatSize: () => '1 KB' }));
it('selects uploads and history while preserving the draft across viewing and clearing', async () => {
  const file = { id: 'one', name: '测试.docx', size: 100, created_at: '2026-10-29' };
  vi.mocked(listFiles).mockResolvedValue({ items: [file], total: 1 });
  vi.mocked(uploadFile).mockResolvedValue(file);
  vi.mocked(readDocument).mockResolvedValue({ file, revision: 'sha', blocks: [], notice: '正文', table_count: 0 });
  const wrapper = mount(App);
  await flushPromises();
  await wrapper.get('textarea').setValue('修改第二个标题');
  wrapper.getComponent(Composer).vm.$emit('upload', new File(['x'], '测试.docx'));
  await flushPromises();
  expect(wrapper.get('.selected-file-name').text()).toBe(file.name);
  expect(wrapper.findComponent(FileDrawer).exists()).toBe(false);
  await wrapper.get('[aria-label="清除当前选中文件"]').trigger('click');
  expect(wrapper.find('.selected-file').exists()).toBe(false);
  expect(wrapper.get('textarea').element.value).toBe('修改第二个标题');
  await wrapper.get('.files-toggle').trigger('click');
  await flushPromises();
  wrapper.getComponent(FileDrawer).vm.$emit('edit', file);
  await flushPromises();
  expect(wrapper.get('.selected-file-name').text()).toBe(file.name);
  await wrapper.get('.files-toggle').trigger('click');
  await flushPromises();
  wrapper.getComponent(FileDrawer).vm.$emit('view', file);
  await flushPromises();
  expect(wrapper.find('textarea').exists()).toBe(false);
  wrapper.getComponent(DocumentEditor).vm.$emit('close');
  await flushPromises();
  expect(wrapper.get('textarea').element.value).toBe('修改第二个标题');
  expect(wrapper.get('.selected-file-name').text()).toBe(file.name);
  expect(wrapper.get('.send-button').attributes('disabled')).toBeDefined();
  await wrapper.get('.files-toggle').trigger('click');
  await flushPromises();
  vi.mocked(listFiles).mockResolvedValue({ items: [], total: 0 });
  wrapper.getComponent(FileDrawer).vm.$emit('deleted', file);
  await flushPromises();
  expect(wrapper.find('.selected-file').exists()).toBe(false);
  expect(wrapper.get('textarea').element.value).toBe('修改第二个标题');
  expect(wrapper.getComponent(FileDrawer).props('total')).toBe(0);
  wrapper.unmount();
});
